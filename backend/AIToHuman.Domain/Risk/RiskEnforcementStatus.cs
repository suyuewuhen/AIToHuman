namespace AIToHuman.Domain.Risk;

/// <summary>
/// 发布之后的风险处置状态。
///
/// 为什么需要它：草稿阶段的判定只回答"现在能不能发布"，而规则可以在任务上线之后被改，
/// 悬赏也可以在任务上线之后被加——一条已经在大厅里（甚至已经被接单）的任务，
/// 可能在新规则下变成"禁止发布"或"需要人工复核"。这时必须有一个明确的状态说明平台做过什么，
/// 而不是让任务带着一条过期的判定继续在线（见 <c>ReassessRisk</c>）。
/// </summary>
public enum RiskEnforcementStatus
{
    /// <summary>没有被风控处置过（正常在线或从未命中）。</summary>
    None,

    /// <summary>
    /// 复检命中"需人工复核"：**任务保持在线**，同时进运营队列等人工复检结论。
    /// 保持在线是有意的——把一条只是需要看一眼的任务直接下架，对需求方和服务者都太粗暴。
    /// </summary>
    RecheckRequired,

    /// <summary>
    /// 已按风控处置：没有订单的直接自动下架；已经有订单的冻结订单，等运营按争议流程处置。
    /// 这条状态只会由"命中禁止类别"产生——平台红线不因为任务已经上线而放宽。
    /// </summary>
    Suspended
}
